#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
合并 TannayeJ/ai-vendor-rules 的 19 个 Clash YAML 规则与本地 personal-ai.list，
输出 Clash / Surge / Loon 三端兼容的标准 classical 纯文本规则集。
"""

import re
import sys
import urllib.request
from pathlib import Path
from typing import Set

AI_VENDORS = [
    "openai", "claude", "gemini", "grok", "mistral", "meta-ai", "perplexity",
    "poe", "openrouter", "github-copilot", "microsoft-copilot", "cursor",
    "windsurf", "midjourney", "stability-ai", "runway", "pika", "suno",
    "elevenlabs",
]

BASE_URL = "https://raw.githubusercontent.com/TannayeJ/ai-vendor-rules/main/generated/clash/{vendor}.yaml"
ALLOWED_TYPES = {"DOMAIN", "DOMAIN-SUFFIX", "DOMAIN-KEYWORD", "IP-CIDR", "IP-CIDR6"}

ROOT = Path(__file__).resolve().parent.parent
PERSONAL_AI = ROOT / "personal-ai.list"
OUTPUT_FILE = ROOT / "generated" / "ai-suite.list"


def fetch_text(url: str, timeout: int = 20) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "personal-proxy-rules-builder/1.0"})
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        if resp.status != 200:
            raise RuntimeError(f"HTTP {resp.status} for {url}")
        return resp.read().decode("utf-8")


def parse_lines(content: str, skipped: list) -> Set[str]:
    rules: Set[str] = set()
    for raw_line in content.splitlines():
        line = raw_line.strip().lstrip("\ufeff")
        if not line or line.startswith("#") or line.startswith("payload:"):
            continue
        if line.startswith("- "):
            line = line[2:].strip()

        line = re.sub(r"\s+#.*$", "", line).strip()
        if (line.startswith("'") and line.endswith("'")) or (
            line.startswith('"') and line.endswith('"')
        ):
            line = line[1:-1].strip()

        parts = [p.strip() for p in line.split(",") if p.strip()]
        if len(parts) < 2:
            continue

        rule_type = parts[0].upper()
        if rule_type not in ALLOWED_TYPES:
            skipped.append(line)
            continue

        value = parts[1].lower() if rule_type in ("DOMAIN", "DOMAIN-SUFFIX", "IP-CIDR", "IP-CIDR6") else parts[1]
        extra = [p.lower() for p in parts[2:] if p.lower() == "no-resolve"]
        rules.add(",".join([rule_type, value] + extra))

    return rules


def main() -> int:
    merged: Set[str] = set()
    skipped = []

    for vendor in AI_VENDORS:
        url = BASE_URL.format(vendor=vendor)
        try:
            text = fetch_text(url)
        except Exception as exc:
            print(f"[ERROR] 拉取失败 {vendor}: {exc}", file=sys.stderr)
            return 1
        merged |= parse_lines(text, skipped)

    if PERSONAL_AI.exists():
        merged |= parse_lines(PERSONAL_AI.read_text(encoding="utf-8"), skipped)

    if len(merged) < 50:
        print(f"[ERROR] 合并结果异常过少（仅 {len(merged)} 条），中止写入。", file=sys.stderr)
        return 1

    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    header = [
        "# Auto-generated by scripts/build_ai_rules.py",
        "# Sources: TannayeJ/ai-vendor-rules (19 vendors) + personal-ai.list",
        f"# Total rules: {len(merged)}",
        "",
    ]
    OUTPUT_FILE.write_text("\n".join(header + sorted(merged)) + "\n", encoding="utf-8")

    print(f"[OK] 已生成 {OUTPUT_FILE}，共 {len(merged)} 条规则。")
    if skipped:
        print(f"[INFO] 已过滤不兼容/非通用条目 ({len(skipped)} 条): {skipped}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
